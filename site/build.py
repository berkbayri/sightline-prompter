# ---------- tiny mustache-style engine: {{x}} escaped, {{{x}}} raw, {{#x}}..{{/x}}, {{^x}}..{{/x}} ----------
TOKEN = re.compile(r"\{\{\{\s*([\w.]+)\s*\}\}\}|\{\{\s*([#^/]?)\s*([\w.]+)\s*\}\}")


def lookup(stack, path):
    if path == ".":
        return stack[-1]["."]
    head, *rest = path.split(".")
    for ctx in reversed(stack):
        if isinstance(ctx, dict) and head in ctx:
            val = ctx[head]
            for k in rest:
                val = val[int(k)] if isinstance(val, list) else val[k]
            return val
    raise KeyError(path)


def parse(tpl):
    root, stack, pos = [], [], 0
    node = root
    for m in TOKEN.finditer(tpl):
        if m.start() > pos:
            node.append(tpl[pos:m.start()])
        pos = m.end()
        if m.group(1):
            node.append(("raw", m.group(1)))
        elif m.group(2) in ("#", "^"):
            child = (m.group(2), m.group(3), [])
            node.append(child)
            stack.append(node)
            node = child[2]
        elif m.group(2) == "/":
            node = stack.pop()
        else:
            node.append(("esc", m.group(3)))
    node.append(tpl[pos:])
    if stack:
        sys.exit("template: unclosed section")
    return root


def render(nodes, stack):
    out = []
    for n in nodes:
        if isinstance(n, str):
            out.append(n)
        elif n[0] == "raw":
            out.append(str(lookup(stack, n[1])))
        elif n[0] == "esc":
            out.append(html.escape(str(lookup(stack, n[1])), quote=True))
        else:
            val = lookup(stack, n[1])
            if n[0] == "^":
                out.append(render(n[2], stack) if not val else "")
            elif isinstance(val, list):
                for item in val:
                    out.append(render(n[2], stack + [item if isinstance(item, dict) else {".": item}]))
            elif val:
                out.append(render(n[2], stack + [val if isinstance(val, dict) else {".": val}]))
    return "".join(out)


# ---------- helpers ----------
def shape(v):
    if isinstance(v, dict):
        return {k: shape(x) for k, x in sorted(v.items())}
    if isinstance(v, list):
        return [shape(x) for x in v]
    return None


def diff(a, b, path=""):
    """Yield key-path mismatches between two shapes (list lengths must match too)."""
    if isinstance(a, dict) and isinstance(b, dict):
        for k in a.keys() | b.keys():
            if k not in a:
                yield f"{path}.{k}: extra key"
            elif k not in b:
                yield f"{path}.{k}: missing key"
            else:
                yield from diff(a[k], b[k], f"{path}.{k}")
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            yield f"{path}: {len(b)} items, en has {len(a)}"
        for i, (x, y) in enumerate(zip(a, b)):
            yield from diff(x, y, f"{path}[{i}]")
    elif type(a) is not type(b) and not (a is None and b is None):
        yield f"{path}: type differs"


def empties(v, path=""):
    if isinstance(v, dict):
        for k, x in v.items():
            yield from empties(x, f"{path}.{k}")
    elif isinstance(v, list):
        for i, x in enumerate(v):
            yield from empties(x, f"{path}[{i}]")
    elif isinstance(v, str) and not v.strip():
        yield path


def file_hash(p):
    return hashlib.md5(p.read_bytes()).hexdigest()[:8]


def webp_size(p):
    """(w, h) from a WebP header; None if unreadable."""
    b = p.read_bytes()[:40]
    if b[:4] != b"RIFF" or b[8:12] != b"WEBP":
        return None
    k = b[12:16]
    if k == b"VP8 ":
        return int.from_bytes(b[26:28], "little") & 0x3FFF, int.from_bytes(b[28:30], "little") & 0x3FFF
    if k == b"VP8L":
        v = int.from_bytes(b[21:25], "little")
        return (v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1
    if k == b"VP8X":
        return int.from_bytes(b[24:27], "little") + 1, int.from_bytes(b[27:30], "little") + 1
    return None


def image(name, default):
    p = SITE / "assets/img" / f"{name}.webp"
    if not p.exists():
        return {"has": False, "url": "", "w": default[0], "h": default[1]}
    w, h = webp_size(p) or default
    return {"has": True, "url": f"/assets/img/{name}.webp?v={file_hash(p)}", "w": w, "h": h}


def store_url(placement):
    q = (f"pt={APPSTORE_PT}&" if APPSTORE_PT else "") + f"ct=site-{placement}"
    return f"{APPSTORE}?{q}"


def loc_path(code):
    return "/" if code == "en" else f"/{code}/"


def ga_snippet():
    if GA_ID == "G-XXXXXXXXXX":
        return ""
    return (
        "<script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments)}"
        "gtag('consent','default',{ad_storage:'denied',ad_user_data:'denied',ad_personalization:'denied',"
        "analytics_storage:'denied',wait_for_update:500});"
        "try{localStorage.getItem('sp-consent')==='granted'&&gtag('consent','update',{analytics_storage:'granted'})}catch(e){}"
        f"gtag('js',new Date());gtag('config','{GA_ID}')</script>\n"
        f'<script async src="https://www.googletagmanager.com/gtag/js?id={GA_ID}"></script>'
    )


def jsonld(t, canonical, lang, faq):
    org = {"@id": SITE_URL + "/#org"}
    graph = [
        {"@type": ["SoftwareApplication", "MobileApplication"], "@id": SITE_URL + "/#app", "name": "Sightline Prompter",
         "operatingSystem": "iOS 17, macOS 14", "applicationCategory": "MultimediaApplication",
         "description": t["meta"]["description"], "url": canonical, "downloadUrl": APPSTORE,
         "image": SITE_URL + "/icon-512.png", "inLanguage": lang, "publisher": org,
         "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD",
                    "description": "Free to download. Sightline Pro is an in-app purchase."}},
        {"@type": "Organization", "@id": SITE_URL + "/#org", "name": "Sightline Prompter", "url": SITE_URL + "/",
         "logo": SITE_URL + "/icon-512.png",
         "contactPoint": {"@type": "ContactPoint", "contactType": "customer support", "email": "hi@sightlineprompter.app"}},
        {"@type": "WebSite", "@id": SITE_URL + "/#site", "url": SITE_URL + "/", "name": "Sightline Prompter",
         "inLanguage": lang, "publisher": org},
        {"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": i["q"], "acceptedAnswer": {"@type": "Answer", "text": i["a"]}} for i in faq]},
    ]
    return json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False,
                      separators=(",", ":")).replace("</", "<\\/")


def make_icons():
    if not ICON.exists():
        print("warn: app icon missing, skipping icons")
        return
    for name, args in [("favicon.ico", ["-s", "format", "ico", "-z", "32", "32"]),
                       ("apple-touch-icon.png", ["-z", "180", "180"]), ("icon-512.png", ["-z", "512", "512"])]:
        if not (DOCS / name).exists():
            subprocess.run(["sips", *args, str(ICON), "--out", str(DOCS / name)], check=True, capture_output=True)


def copy_assets():
    dst = DOCS / "assets"
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(SITE / "assets", dst, ignore=shutil.ignore_patterns("src", ".DS_Store", "*.json"))


def main():
    en_path = SITE / "i18n/en.json"
    if not en_path.exists():
        sys.exit("site/i18n/en.json is missing")
    en = json.loads(en_path.read_text(encoding="utf-8"))
    en_shape = shape(en)
    built, bad = {}, False
    for code, *_ in LOCALES:
        p = SITE / f"i18n/{code}.json"
        if not p.exists():
            print(f"skip {code}: no JSON yet")
            continue
        t = json.loads(p.read_text(encoding="utf-8"))
        problems = list(diff(en_shape, shape(t)))
        if problems:
            bad = True
            print(f"ERROR {code}.json differs from en.json:\n  " + "\n  ".join(sorted(problems)), file=sys.stderr)
        for e in empties(t):
            print(f"warn {code}.json: empty value at {e}")
        built[code] = t
    if bad:
        sys.exit(1)

    DOCS.mkdir(exist_ok=True)
    copy_assets()
    make_icons()
    og = SITE / "assets/img/og.png"
    og_url = f"{SITE_URL}/assets/img/og.png?v={file_hash(og)}" if og.exists() else SITE_URL + "/icon-512.png"
    tpl = parse((SITE / "template.html").read_text(encoding="utf-8"))
    v = {"css": file_hash(SITE / "assets/site.css"), "js": file_hash(SITE / "assets/site.js")}
    analytics = GA_ID != "G-XXXXXXXXXX"
    meta = {c: (lang, ogl, name, skip) for c, lang, ogl, name, skip in LOCALES}
    switcher = lambda cur: [{"code": c, "path": loc_path(c), "name": meta[c][2], "lang": meta[c][0],
                             "current": c == cur} for c in built]

    top, foot = (parse((SITE / f"partials/{n}.html").read_text(encoding="utf-8")) for n in ("top", "foot"))

    def context(code, t, home):
        lang, ogl, _, skip = meta[code]
        store = dict(t["store"], **{f"url_{p}": store_url(p) for p in PLACEMENTS})
        store["badge"] = BADGE + t["store"]["badge_lang"]
        cases = dict(t["cases"], items=[
            dict(it, idx=i, selected="true" if i == 0 else "false", hidden="" if i == 0 else " hidden",
                 tabindex=0 if i == 0 else -1, img=image(CASE_IMG[it["id"]], CASE_DIMS))
            for i, it in enumerate(t["cases"]["items"])])
        ctx = dict(
            t, lang=lang, code=code, og_locale=ogl, og_image=og_url, skip=skip, home=home,
            locales=",".join(built), store=store, cases=cases, v=v, analytics=analytics, ga=ga_snippet(),
            gsc=f'<meta name="google-site-verification" content="{html.escape(GSC_TOKEN)}">\n' if GSC_TOKEN else "",
            # width estimate in em for the hero line: wide scripts 1em/char, latin ~.52em/char
            hero_w=round(sum(1.0 if ord(ch) > 0x2E80 else .52 for ch in t["hero"]["lines"][1]), 1),
            year=date.today().year, phone=image("iphone-preview-person", PHONE_DIMS),
            alternates=[{"hreflang": meta[c][0], "url": SITE_URL + loc_path(c)} for c in built],
            og_alternates=[{"og": meta[c][1]} for c in built if c != code], switcher=switcher(code),
            wall=[{"name": n, "lang": l} for n, l in WALL], x_default=SITE_URL + "/",
            demo=[{"line": s, "first": i == 0, "cue_after": i == 0} for i, s in enumerate(
                s for s in re.split(r"(?<=[.!?。！？])\s*", t["devices"]["demo_script"].strip()) if s)],
        )
        ctx["chrome_top"], ctx["chrome_foot"] = render(top, [ctx]), render(foot, [ctx])
        return ctx

    for code, t in built.items():
        canonical = SITE_URL + loc_path(code)
        ctx = context(code, t, loc_path(code))
        ctx.update(canonical=canonical, jsonld=jsonld(t, canonical, meta[code][0], t["faq"]["items"]))
        out = DOCS / "index.html" if code == "en" else DOCS / code / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(render(tpl, [ctx]), encoding="utf-8")
        print("wrote", out.relative_to(ROOT))

    # English-only long-form pages: same chrome, content from site/pages/<slug>.html
    page_tpl = parse((SITE / "page.html").read_text(encoding="utf-8"))
    for slug, (title, desc) in PAGES.items():
        ctx = context("en", built["en"], "/")
        ctx.update(canonical=f"{SITE_URL}/{slug}.html", page={"title": title, "description": desc})
        ctx["content"] = render(parse((SITE / f"pages/{slug}.html").read_text(encoding="utf-8")), [ctx])
        out = DOCS / f"{slug}.html"
        # a hand-written page is only replaced on request: python3 site/build.py --replace-pages
        if out.exists() and GENERATED not in out.read_text(encoding="utf-8") and "--replace-pages" not in sys.argv:
            print(f"kept hand-written docs/{slug}.html (build.py --replace-pages replaces it)")
            continue
        out.write_text(render(page_tpl, [ctx]), encoding="utf-8")
        print("wrote", f"docs/{slug}.html")

    alts = "".join(f'<xhtml:link rel="alternate" hreflang="{meta[c][0]}" href="{SITE_URL}{loc_path(c)}"/>' for c in built)
    alts += f'<xhtml:link rel="alternate" hreflang="x-default" href="{SITE_URL}/"/>'
    urls = "".join(f"<url><loc>{SITE_URL}{loc_path(c)}</loc><lastmod>{date.today()}</lastmod>{alts}</url>" for c in built)
    urls += "".join(f"<url><loc>{SITE_URL}/{p}.html</loc><lastmod>{date.today()}</lastmod></url>" for p in PAGES)
    (DOCS / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
        f'xmlns:xhtml="http://www.w3.org/1999/xhtml">{urls}</urlset>\n', encoding="utf-8")
    (DOCS / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {SITE_URL}/sitemap.xml\n", encoding="utf-8")
    (DOCS / "CNAME").write_text("sightlineprompter.app\n", encoding="utf-8")
    (DOCS / "404.html").write_text(
        '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
        '<meta name="robots" content="noindex"><title>Page not found | Sightline Prompter</title>'
        f'<link rel="icon" href="/favicon.ico" sizes="any"><link rel="stylesheet" href="/assets/site.css?v={v["css"]}"></head>'
        '<body class="nf"><main class="wrap nf-main"><p class="reading"><span class="ln">'
        '<span class="w c">404</span></span></p><h1 class="nf-title">Page not found</h1>'
        '<p class="sub">This page is not part of the site.</p>'
        '<p><a class="link" href="/">Back to Sightline Prompter</a></p></main></body></html>\n', encoding="utf-8")
    print(f"ok: {len(built)} locale(s), analytics {'on' if analytics else 'off (GA_ID is the placeholder)'}")


if __name__ == "__main__":
    main()
