def html_attr_json(o):
    return json.dumps(o, ensure_ascii=False, separators=(",", ":"))


def make_icons():
    if not ICON.exists():
        print("warn: app icon missing, skipping icons")
        return
    for name, args in [("favicon.ico", ["-s", "format", "ico", "-z", "32", "32"]),
                       ("apple-touch-icon.png", ["-z", "180", "180"]), ("icon-512.png", ["-z", "512", "512"])]:
        if not (DOCS / name).exists():
            subprocess.run(["sips", *args, str(ICON), "--out", str(DOCS / name)], check=True, capture_output=True)


def copy_assets():
    dst = DOCS / "assets"
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(SITE / "assets", dst, ignore=shutil.ignore_patterns("src", ".DS_Store", "*.json", "README.md"))


def main():
    en_path = SITE / "i18n/en.json"
    if not en_path.exists():
        sys.exit("site/i18n/en.json is missing")
    en = json.loads(en_path.read_text(encoding="utf-8"))
    en_shape = shape(en)
    built, bad = {}, False
    for code, *_ in LOCALES:
        p = SITE / f"i18n/{code}.json"
        if not p.exists():
            print(f"skip {code}: no JSON yet")
            continue
        t = json.loads(p.read_text(encoding="utf-8"))
        problems = list(diff(en_shape, shape(t)))
        if problems:
            bad = True
            print(f"ERROR {code}.json differs from en.json:\n  " + "\n  ".join(sorted(problems)), file=sys.stderr)
        for e in empties(t):
            print(f"warn {code}.json: empty value at {e}")
        built[code] = t
    if bad:
        sys.exit(1)

    DOCS.mkdir(exist_ok=True)
    copy_assets()
    make_icons()
    og = SITE / "assets/img/og.png"
    og_url = f"{SITE_URL}/assets/img/og.png?v={file_hash(og)}" if og.exists() else SITE_URL + "/icon-512.png"
    tpl = parse((SITE / "template.html").read_text(encoding="utf-8"))
    v = {"css": file_hash(SITE / "assets/site.css"), "js": file_hash(SITE / "assets/site.js"), "pjs": file_hash(SITE / "assets/prompter.js"),
         "editorial": file_hash(SITE / "assets/editorial.css")}
    analytics = GA_ID != "G-XXXXXXXXXX"
    meta = {c: (lang, ogl, name, skip) for c, lang, ogl, name, skip in LOCALES}
    switcher = lambda cur: [{"code": c, "path": loc_path(c), "name": meta[c][2], "lang": meta[c][0],
                             "current": c == cur} for c in built]

    top, foot = (parse((SITE / f"partials/{n}.html").read_text(encoding="utf-8")) for n in ("top", "foot"))

    def context(code, t, home):
        lang, ogl, _, skip = meta[code]
        store = dict(t["store"], **{f"url_{p}": store_url(p) for p in PLACEMENTS})
        store["badge"] = BADGE + t["store"]["badge_lang"]
        lp = live_prompter(code)
        case_bg = {"youtube": lp["bg_l"], "reels": lp["bg"]["reels"], "course": lp["bg"]["course"], "meeting": lp["mac_meeting"]}
        cases = dict(t["cases"], items=[
            dict(it, idx=i, selected="true" if i == 0 else "false", hidden="" if i == 0 else " hidden",
                 tabindex=0 if i == 0 else -1,
                 orient={k: CASE_ORIENT[it["id"]] == k for k in ("p", "l", "mac")},
                 pr=lp[CASE_LIVE[it["id"]]], prbg=case_bg[it["id"]])
            for i, it in enumerate(t["cases"]["items"])])
        ctx = dict(
            t, lang=lang, code=code, og_locale=ogl, og_image=og_url, skip=skip, home=home,
            locales=",".join(built), store=store, cases=cases, v=v, analytics=analytics, ga=ga_snippet(),
            gsc=f'<meta name="google-site-verification" content="{html.escape(GSC_TOKEN)}">\n' if GSC_TOKEN else "",
            # width estimate in em for the hero line: wide scripts 1em/char, latin ~.52em/char
            hero_w=reading_width(t["hero"]["lines"], t["hero"]["cue"].strip("[]")), hero_cue=t["hero"]["cue"].strip("[]"),
            dev={"frame_p": asset("img/devices/iphone-frame-portrait.webp"), "frame_l": asset("img/devices/iphone-frame-landscape.webp"),
                 "mac_frame": asset("img/devices/macbook-frame.webp")},
            # the live prompter (assets/prompter.js): the approved scripts as the app splits them, over stills of each screen
            lp=lp,
            # distance scene frames rendered by site/render (one per 5 cm); the version follows the 35 cm frame
            maclib=image(f"devices/{code}/mac-library" if (SITE / "assets/img/devices" / code / "mac-library.webp").exists() else "devices/en/mac-library", (1600, 996)),
            lang_offers="" if code != "en" else html_attr_json({c: [t2["nav"]["lang_offer"], loc_path(c)] for c, t2 in built.items() if c != "en"}),
            year=date.today().year, phone=image("iphone-preview-person", PHONE_DIMS),
            alternates=[{"hreflang": meta[c][0], "url": SITE_URL + loc_path(c)} for c in built],
            og_alternates=[{"og": meta[c][1]} for c in built if c != code], switcher=switcher(code),
            wall=[{"name": n, "lang": l} for n, l in WALL], x_default=SITE_URL + "/",
            demo=[{"line": s, "first": i == 0, "cue_after": i == 0} for i, s in enumerate(
                s for s in re.split(r"(?<=[.!?。！？])\s*", t["devices"]["demo_script"].strip()) if s)],
        )
        ctx["chrome_top"], ctx["chrome_foot"] = render(top, [ctx]), render(foot, [ctx])
        return ctx

    for code, t in built.items():
        canonical = SITE_URL + loc_path(code)
        ctx = context(code, t, loc_path(code))
        ctx.update(canonical=canonical, jsonld=jsonld(t, canonical, meta[code][0], t["faq"]["items"]))
        card = make_og(code, t, meta[code][0])
        if card:
            ctx["og_image"] = f"{SITE_URL}/assets/og/{code}.png?v={file_hash(card)}"
        out = DOCS / "index.html" if code == "en" else DOCS / code / "index.html"
        out.parent.mkdir(exist_ok=True)
        page = render(tpl, [ctx])
        if code != "en":
            page = mark_brands(page)
        out.write_text(page, encoding="utf-8")
        print("wrote", out.relative_to(ROOT))

    # English-only long-form pages: same chrome, content from site/pages/<slug>.html
    page_tpl = parse((SITE / "page.html").read_text(encoding="utf-8"))
    for slug, (title, desc) in PAGES.items():
        ctx = context("en", built["en"], "/")
        ctx.update(canonical=f"{SITE_URL}/{slug}.html", page={"title": title, "description": desc})
        ctx["content"] = render(parse((SITE / f"pages/{slug}.html").read_text(encoding="utf-8")), [ctx])
        out = DOCS / f"{slug}.html"
        # a hand-written page is only replaced on request: python3 site/build.py --replace-pages
        if out.exists() and GENERATED not in out.read_text(encoding="utf-8") and "--replace-pages" not in sys.argv:
            print(f"kept hand-written docs/{slug}.html (build.py --replace-pages replaces it)")
            continue
        out.write_text(render(page_tpl, [ctx]), encoding="utf-8")
        print("wrote", f"docs/{slug}.html")

    alts = "".join(f'<xhtml:link rel="alternate" hreflang="{meta[c][0]}" href="{SITE_URL}{loc_path(c)}"/>' for c in built)
    alts += f'<xhtml:link rel="alternate" hreflang="x-default" href="{SITE_URL}/"/>'
    # lastmod = the day the page's own inputs last changed, so crawlers can trust it
    stamp = lambda *fs: date.fromtimestamp(max(f.stat().st_mtime for f in fs))
