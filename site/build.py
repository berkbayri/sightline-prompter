# ---------- tiny mustache-style engine: {{x}} escaped, {{{x}}} raw, {{#x}}..{{/x}}, {{^x}}..{{/x}} ----------
TOKEN = re.compile(r"\{\{\{\s*([\w.]+)\s*\}\}\}|\{\{\s*([#^/]?)\s*([\w.]+)\s*\}\}")


def lookup(stack, path):
    if path == ".":
        return stack[-1]["."]
    head, *rest = path.split(".")
    for ctx in reversed(stack):
        if isinstance(ctx, dict) and head in ctx:
            val = ctx[head]
            for k in rest:
                val = val[int(k)] if isinstance(val, list) else val[k]
            return val
    raise KeyError(path)


def parse(tpl):
    root, stack, pos = [], [], 0
    node = root
    for m in TOKEN.finditer(tpl):
        if m.start() > pos:
            node.append(tpl[pos:m.start()])
        pos = m.end()
        if m.group(1):
            node.append(("raw", m.group(1)))
        elif m.group(2) in ("#", "^"):
            child = (m.group(2), m.group(3), [])
            node.append(child)
            stack.append(node)
            node = child[2]
        elif m.group(2) == "/":
            node = stack.pop()
        else:
            node.append(("esc", m.group(3)))
    node.append(tpl[pos:])
    if stack:
        sys.exit("template: unclosed section")
    return root


# English brand names inside uppercased text get lang="en", so a tr page shows "IPHONE", never "İPHONE".
BRANDS = re.compile(r"\b(iPhone|iPad|iCloud|MacBook|Mac|Sightline Prompter|Sightline Pro|Sightline|TikTok|YouTube|DualSense|ProRes|App Store)\b")
UPPER_BLOCKS = re.compile(r"(<h2\b[^>]*>.*?</h2>|<li class=\"tag\">.*?</li>|<h3\b[^>]*>.*?</h3>)", re.S)


def mark_brands(page):
    def in_text(block):
        # only touch text between tags, never attributes
        return re.sub(r">([^<]+)<", lambda t: ">" + BRANDS.sub(r'<span lang="en">\1</span>', t.group(1)) + "<", block.group(0))
    return UPPER_BLOCKS.sub(in_text, page)


assert mark_brands('<h2><em>iPhone\'da kaydet.</em></h2><img alt="iPhone">') == '<h2><em><span lang="en">iPhone</span>\'da kaydet.</em></h2><img alt="iPhone">'


def render(nodes, stack):
    out = []
    for n in nodes:
        if isinstance(n, str):
            out.append(n)
        elif n[0] == "raw":
            out.append(str(lookup(stack, n[1])))
        elif n[0] == "esc":
            out.append(html.escape(str(lookup(stack, n[1])), quote=True))
        else:
            val = lookup(stack, n[1])
            if n[0] == "^":
                out.append(render(n[2], stack) if not val else "")
            elif isinstance(val, list):
                for item in val:
                    out.append(render(n[2], stack + [item if isinstance(item, dict) else {".": item}]))
            elif val:
                out.append(render(n[2], stack + [val if isinstance(val, dict) else {".": val}]))
    return "".join(out)


# ---------- helpers ----------
def shape(v):
    if isinstance(v, dict):
        return {k: shape(x) for k, x in sorted(v.items())}
    if isinstance(v, list):
        return [shape(x) for x in v]
    return None


def diff(a, b, path=""):
    """Yield key-path mismatches between two shapes (list lengths must match too)."""
    if isinstance(a, dict) and isinstance(b, dict):
        for k in a.keys() | b.keys():
            if k not in a:
                yield f"{path}.{k}: extra key"
            elif k not in b:
                yield f"{path}.{k}: missing key"
            else:
                yield from diff(a[k], b[k], f"{path}.{k}")
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            yield f"{path}: {len(b)} items, en has {len(a)}"
        for i, (x, y) in enumerate(zip(a, b)):
            yield from diff(x, y, f"{path}[{i}]")
    elif type(a) is not type(b) and not (a is None and b is None):
        yield f"{path}: type differs"


def empties(v, path=""):
    if isinstance(v, dict):
        for k, x in v.items():
            yield from empties(x, f"{path}.{k}")
    elif isinstance(v, list):
        for i, x in enumerate(v):
            yield from empties(x, f"{path}[{i}]")
    elif isinstance(v, str) and not v.strip():
        yield path


def file_hash(p):
    return hashlib.md5(p.read_bytes()).hexdigest()[:8]


def webp_size(p):
    """(w, h) from a WebP header; None if unreadable."""
    b = p.read_bytes()[:40]
    if b[:4] != b"RIFF" or b[8:12] != b"WEBP":
        return None
    k = b[12:16]
    if k == b"VP8 ":
        return int.from_bytes(b[26:28], "little") & 0x3FFF, int.from_bytes(b[28:30], "little") & 0x3FFF
    if k == b"VP8L":
        v = int.from_bytes(b[21:25], "little")
        return (v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1
    if k == b"VP8X":
        return int.from_bytes(b[24:27], "little") + 1, int.from_bytes(b[27:30], "little") + 1
    return None


RESIZE = shutil.which("magick")


def image(name, default, locale=None):
    """Image under assets/img; with `locale`, the localized copy assets/img/<locale>/<name>.webp when it exists."""
    if locale and (SITE / "assets/img" / locale / f"{name}.webp").exists():
        name = f"{locale}/{name}"
    p = SITE / "assets/img" / f"{name}.webp"
    if not p.exists():
        return {"has": False, "url": "", "w": default[0], "h": default[1]}
    w, h = webp_size(p) or default
    v = file_hash(p)
    url = f"/assets/img/{name}.webp?v={v}"
    parts = []
    if RESIZE:  # two smaller copies so phones do not download the 2868 px original
        for x in (round(w * .4), round(w * .7)):
            dst = DOCS / "assets/img" / f"{name}-{x}.webp"
            dst.parent.mkdir(parents=True, exist_ok=True)
            if not dst.exists():
                subprocess.run([RESIZE, str(p), "-resize", f"{x}x", "-quality", "80", str(dst)], check=True, capture_output=True)
            parts.append(f"/assets/img/{name}-{x}.webp?v={v} {x}w")
    return {"has": True, "url": url, "w": w, "h": h, "srcset": ", ".join(parts + [f"{url} {w}w"])}


